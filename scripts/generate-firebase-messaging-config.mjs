#!/usr/bin/env node
/**
 * Writes public/firebase-messaging-config.js for the service worker.
 * Reads NEXT_PUBLIC_FIREBASE_* from .env.local then .env (same order as env-verify).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUT = path.join(ROOT, 'public', 'firebase-messaging-config.js')
const FIREBASE_PUBLIC_DIR = path.join(ROOT, 'public', 'firebase')

const FIREBASE_COMPAT_FILES = [
  'firebase-app-compat.js',
  'firebase-messaging-compat.js',
]

function copyFirebaseCompatForServiceWorker() {
  fs.mkdirSync(FIREBASE_PUBLIC_DIR, { recursive: true })

  for (const file of FIREBASE_COMPAT_FILES) {
    const src = path.join(ROOT, 'node_modules', 'firebase', file)
    const dest = path.join(FIREBASE_PUBLIC_DIR, file)

    if (!fs.existsSync(src)) {
      console.warn(`Skip ${file}: not found at ${src} (run npm install)`)
      continue
    }

    fs.copyFileSync(src, dest)
    console.log(`Copied ${file} → public/firebase/${file}`)
  }
}

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return
  for (const rawLine of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const idx = line.indexOf('=')
    if (idx <= 0) continue
    const key = line.slice(0, idx).trim()
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) continue
    let value = line.slice(idx + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (process.env[key] == null) process.env[key] = value
  }
}

loadEnvFile(path.join(ROOT, '.env.local'))
loadEnvFile(path.join(ROOT, '.env'))

function cleanFirebaseEnvValue(raw) {
  let value = String(raw ?? '').trim()
  for (let i = 0; i < 8; i++) {
    value = value.replace(/,\s*$/, '').trim()
    const unwrapped = value.replace(/^\\?["']+|\\?["']+$/g, '').trim()
    if (unwrapped === value) break
    value = unwrapped
  }
  return value
}

function pickEnv(name, legacyName) {
  return cleanFirebaseEnvValue(process.env[name] ?? process.env[legacyName] ?? '')
}

const config = {
  apiKey: pickEnv('NEXT_PUBLIC_FIREBASE_API_KEY', 'apiKey'),
  authDomain: pickEnv('NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN', 'authDomain'),
  projectId: pickEnv('NEXT_PUBLIC_FIREBASE_PROJECT_ID', 'projectId'),
  messagingSenderId: pickEnv('NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID', 'messagingSenderId'),
  appId: pickEnv('NEXT_PUBLIC_FIREBASE_APP_ID', 'appId'),
}

const content = `// Generated by scripts/generate-firebase-messaging-config.mjs — do not edit manually.
self.__FIREBASE_WEB_CONFIG__ = ${JSON.stringify(config, null, 2)};
`

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, content, 'utf8')
console.log(`Wrote ${OUT} (projectId=${config.projectId || '(empty)'})`)

copyFirebaseCompatForServiceWorker()
